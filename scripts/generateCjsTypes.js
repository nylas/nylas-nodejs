const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const entryPoint = path.join(__dirname, '..', 'src', 'nylas.ts');
const program = ts.createProgram([entryPoint], {
  target: ts.ScriptTarget.ES2021,
  module: ts.ModuleKind.CommonJS,
  moduleResolution: ts.ModuleResolutionKind.Node10,
});
const checker = program.getTypeChecker();
const source = program.getSourceFile(entryPoint);
const exportedNames = checker
  .getExportsOfModule(checker.getSymbolAtLocation(source))
  .map((symbol) => symbol.getName())
  .filter((name) => name !== 'default')
  .sort();

const aliases = exportedNames.map(
  (name) => `  export import ${name} = models.${name};`
);
const declaration = `// This file is generated by scripts/generateCjsTypes.js
import NylasClass from './lib/types/nylas.js';
import * as models from './lib/types/models/index.js';

declare class Nylas extends NylasClass {
  static default: typeof Nylas;
}

declare namespace Nylas {
${aliases.join('\n')}
}

export = Nylas;
`;

fs.writeFileSync(path.join(__dirname, '..', 'cjs-wrapper.d.ts'), declaration);
